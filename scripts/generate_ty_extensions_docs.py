"""Generate the ty-extensions reference documentation from its vendored stub files."""

import ast
from inspect import cleandoc
from itertools import pairwise
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STUB_FILE = ROOT / "ruff/crates/ty_vendored/ty_extensions/__init__.pyi"
OUTPUT = ROOT / "docs/reference/ty-extensions.md"


def render_docs(stub_file: Path) -> str:
    module = ast.parse(stub_file.read_text(encoding="utf-8"), filename=stub_file)
    sections = [
        (
            "<!-- This file is generated by scripts/generate_ty_extensions_docs.py. "
            "Edit the docstrings in the vendored ty_extensions/__init__.pyi stub. -->"
        ),
        "# ty-extensions",
    ]
    if docstring := ast.get_docstring(module):
        sections.append(docstring)

    for node, following in pairwise([*module.body, None]):
        match node:
            case (
                ast.FunctionDef(name=name)
                | ast.AsyncFunctionDef(name=name)
                | ast.ClassDef(name=name)
            ):
                docstring = ast.get_docstring(node)
            case (
                ast.AnnAssign(target=ast.Name(id=name))
                | ast.Assign(targets=[ast.Name(id=name)])
                | ast.TypeAlias(name=ast.Name(id=name))
            ):
                # Attribute docstrings are standalone strings after the declaration, e.g.
                #
                #     Not: _SpecialForm
                #     """..."""

                match following:
                    case ast.Expr(value=ast.Constant(value=str(value))):
                        docstring = cleandoc(value)
                    case _:
                        docstring = None
            case _:
                continue

        if docstring and not name.startswith("_"):
            sections.append(f"## `{name}`\n\n{docstring}")

    return "\n\n".join(sections) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render_docs(STUB_FILE), encoding="utf-8")
